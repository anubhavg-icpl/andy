/**
 * panes.ts — multi-pane Andy: tmux prefix keys plus a mailbox so the panes'
 * agents can talk.
 *
 * What this module is: the tmux plumbing behind `andy --panes` (port of
 * zimzilla/panes.py). ctrl+b h/v split the window and start a new Andy in the
 * pane; every pane is a separate Andy process with its own Agent, sharing a
 * per-session mailbox directory through the agent_peers/agent_send/agent_inbox
 * tools.
 *
 * Invariants:
 *  - Nested tmux needs the prefix TWICE: an outer server reads ctrl+b first
 *    and never forwards it, so the generated config binds C-b to send-prefix
 *    and the status bar says so when nesting is detected — a hint that omits
 *    that is the difference between the feature working and looking broken.
 *  - `tmux -f` is read only at server START, so applyConfig sources the
 *    config into whatever server is already on our socket; a pre-existing
 *    server would otherwise silently keep tmux's stock bindings.
 *  - A mailbox is a conversation, not a file transfer: bodies cap at
 *    MAX_MESSAGE_CHARS, one JSON line per message.
 *  - Nothing here touches the network. The mailbox is local to the machine.
 */

import {
  appendFileSync,
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  statSync,
  truncateSync,
  writeFileSync,
} from 'node:fs';
import path from 'node:path';
import { spawn, spawnSync } from 'node:child_process';
import type { ChatMessage, ContentBlock } from './shared.js';

/** Environment variable naming the mailbox session. Set in tmux's global
 *  session environment by the generated config, so every pane inherits it. */
export const ENV_SESSION = 'ANDY_PANE_SESSION';

/**
 * A request from the running TUI to re-open this session under tmux.
 *
 * `/panes` cannot start tmux from inside a running Ink app: tmux has to own
 * the terminal, and the app is holding it. So the command saves the
 * conversation, hands one of these to the app's exit seam
 * (ui/app.relaunchRequest), and cli.ts performs the relaunch once the
 * terminal is free again.
 *
 * `resume` is the session file the new process should pick the conversation
 * back up from, or null to start clean.
 */
export class Relaunch {
  readonly resume: string | null;

  constructor(opts: { resume?: string | null } | string | null = null) {
    this.resume = typeof opts === 'string' ? opts : (opts?.resume ?? null);
  }
}

/** tmux server socket used by the pane launcher, so Andy panes do not
 *  collide with the operator's own tmux. */
export const TMUX_SOCKET = 'andy';
export const TMUX_SESSION = 'andy';

/** Cap on one message body. A mailbox is a conversation, not a file transfer. */
export const MAX_MESSAGE_CHARS = 8000;

const SAFE_RE = /[^A-Za-z0-9._-]+/g;

/** One stored message (Python's ad-hoc dict record). */
export interface PaneMessage {
  from: string;
  to: string;
  /** Epoch seconds. */
  at: number;
  body: string;
}

// === SECTION === tmux config ===

/** True when this process already sits inside somebody else's tmux.
 *
 *  tmux exports TMUX in every pane it creates, so its presence here means
 *  the operator started `andy --panes` from a shell that is itself in a tmux
 *  session. That outer server reads the prefix first and never forwards it,
 *  so ctrl+b h splits the *outer* session and this one looks inert. */
export function nestedInTmux(): boolean {
  return Boolean(process.env['TMUX']);
}

/** shlex.quote: leave safe strings bare, single-quote the rest. */
function shellQuote(s: string): string {
  if (s === '') return "''";
  return /^[A-Za-z0-9_@%+=:,./-]+$/.test(s) ? s : `'${s.replace(/'/g, `'\\''`)}'`;
}

/**
 * The tmux config that gives ctrl+b h and ctrl+b v their meaning.
 *
 * `andyCmd` is the command a new pane runs. It is shell-quoted here so a path
 * with spaces survives tmux's own command parsing.
 *
 * `nested` only changes what the status bar SAYS: when an outer tmux owns the
 * prefix the bindings need it pressed twice, and a hint that omits that is
 * the difference between the feature working and looking broken.
 */
export function tmuxConf(andyCmd: string, nested = false): string {
  const cmd = shellQuote(andyCmd);
  const hint = nested
    ? ' ctrl+b ctrl+b h · ctrl+b ctrl+b v (outer tmux takes the prefix) '
    : ' ctrl+b h split-right · ctrl+b v split-down ';
  return [
    '# Andy panes — generated by `andy --panes`.',
    'set -g prefix C-b',
    'unbind C-b',
    // Doubling the prefix is what forwards one to the outer server, which is
    // the only way to reach these bindings when nested. Harmless standalone.
    'bind C-b send-prefix',
    'set -g mouse on',
    'set -g base-index 1',
    'set -g pane-base-index 1',
    "set -g status-style 'bg=#040704,fg=#00ff41'",
    "set -g status-left '[andy] '",
    `set -g status-right '${hint}'`,
    'set -g escape-time 10',
    'set -g history-limit 20000',
    // Global session environment: every pane tmux creates inherits it, so
    // the mailbox session is known to every Andy without per-bind -e.
    `set-environment -g ${ENV_SESSION} ${TMUX_SESSION}`,
    '',
    '# prefix + h : new Andy pane to the right (horizontal split)',
    `bind h split-window -h -c '#{{pane_current_path}}' ${cmd}`,
    '# prefix + v : new Andy pane below (vertical split)',
    `bind v split-window -v -c '#{{pane_current_path}}' ${cmd}`,
    '',
  ].join('\n');
}

/**
 * Write the config under the state dir and return its path.
 *
 * `nested` defaults to nestedInTmux(), so the caller only passes it to
 * override what the environment says.
 */
export function writeTmuxConf(
  stateDir: string,
  andyCmd: string,
  nested?: boolean | null,
): string {
  const isNested = nested ?? nestedInTmux();
  const p = path.join(stateDir, 'panes', 'tmux.conf');
  mkdirSync(path.dirname(p), { recursive: true });
  writeFileSync(p, tmuxConf(andyCmd, isNested));
  return p;
}

function isFile(p: string): boolean {
  try {
    return statSync(p).isFile();
  } catch {
    return false;
  }
}

function which(name: string): string | null {
  const dirs = (process.env['PATH'] ?? '').split(path.delimiter).filter(Boolean);
  for (const dir of dirs) {
    const cand = path.join(dir, name);
    if (isFile(cand)) return cand;
  }
  return null;
}

export function tmuxAvailable(): boolean {
  return which('tmux') !== null;
}

// === SECTION === identity ===

/** The mailbox session this process belongs to, or null outside panes. */
export function currentSession(): string | null {
  return process.env[ENV_SESSION] || null;
}

/** This pane's agent name. tmux sets TMUX_PANE in every pane itself. */
export function currentAgent(): string | null {
  const pane = tmuxPaneId();
  return pane ? agentNameForPane(pane) : null;
}

/** A filesystem-safe agent name from a tmux pane id like `%3`. */
export function agentNameForPane(paneId: string): string {
  return paneId.trim().replace(/^%+/, '').replace(SAFE_RE, '') || 'pane';
}

/** A name safe to use as one filename: no separators, no leading dots. */
function safeName(name: string): string {
  return String(name ?? '')
    .trim()
    .replace(SAFE_RE, '')
    .replace(/^\.+/, '');
}

// === SECTION === mailbox ===

/** Serialize cross-call access to one inbox file within this process.
 *
 *  Python took an fcntl.flock around each append/rewrite, which also
 *  serialised separate PROCESSES; Node's stdlib has no flock. The practical
 *  equivalent used here: a per-path in-process mutex (the concurrent senders
 *  that matter are the peers' tool calls in this and sibling processes) plus
 *  a single O_APPEND write per message — POSIX guarantees a lone append
 *  write of one small buffer lands whole, so two processes cannot interleave
 *  a line. */
const fileLocks = new Map<string, Promise<unknown>>();

function withFileLock<T>(key: string, fn: () => Promise<T>): Promise<T> {
  const prev = fileLocks.get(key) ?? Promise.resolve();
  const next = prev.then(fn, fn);
  fileLocks.set(
    key,
    next.catch(() => {}),
  );
  return next;
}

export function mailboxRoot(stateDir: string, session: string): string {
  const d = path.join(stateDir, 'panes', safeName(session));
  mkdirSync(d, { recursive: true });
  return d;
}

/** Create this agent's inbox so its peers can find it. Idempotent. */
export function register(root: string, agent: string): void {
  const name = safeName(agent);
  if (name) {
    const p = inboxPath(root, name);
    if (!existsSync(p)) writeFileSync(p, '');
  }
}

function inboxPath(root: string, agent: string): string {
  return path.join(root, `${safeName(agent)}.jsonl`);
}

/** Every agent with an inbox in this session, sorted. */
export function knownAgents(root: string): string[] {
  try {
    return readdirSync(root)
      .filter((f) => f.endsWith('.jsonl'))
      .map((f) => f.replace(/\.jsonl$/, ''))
      .sort();
  } catch {
    return [];
  }
}

/**
 * Append a message to `to`'s inbox. Returns the stored record.
 *
 * Throws Error for an unknown recipient or an empty body (Python ValueError),
 * so the tool layer can report it to the model instead of silently dropping
 * the message.
 */
export function send(root: string, sender: string, to: string, body: string): Promise<PaneMessage> {
  return withFileLock(`send:${root}`, async () => {
    let text = String(body ?? '').trim();
    if (!text) throw new Error('message body is empty');
    const recipient = safeName(to);
    if (!recipient) throw new Error('recipient name is empty');
    if (!knownAgents(root).includes(recipient) && recipient !== safeName(sender)) {
      const known = knownAgents(root);
      throw new Error(
        `no agent named '${to}' in this session — known: ${known.join(', ') || 'none'}`,
      );
    }
    if (text.length > MAX_MESSAGE_CHARS) {
      text = text.slice(0, MAX_MESSAGE_CHARS) + ' …[truncated]';
    }
    const record: PaneMessage = {
      from: safeName(sender) || 'unknown',
      to: recipient,
      at: Date.now() / 1000,
      body: text,
    };
    // One write of one line under O_APPEND: a concurrent appender cannot
    // split this line (see the lock note above).
    appendFileSync(inboxPath(root, recipient), JSON.stringify(record) + '\n');
    return record;
  });
}

/** Return and remove every unread message for `agent`, oldest first. */
export function drain(root: string, agent: string): Promise<PaneMessage[]> {
  return withFileLock(`send:${root}`, async () => {
    const p = inboxPath(root, agent);
    if (!existsSync(p)) return [];
    const out: PaneMessage[] = [];
    for (const line of readFileSync(p, 'utf8').split('\n')) {
      const trimmed = line.trim();
      if (!trimmed) continue;
      try {
        out.push(JSON.parse(trimmed) as PaneMessage);
      } catch {
        continue;
      }
    }
    truncateSync(p, 0);
    return out;
  });
}

/** Render received messages as a block the model can read. */
export function formatMessages(messages: PaneMessage[]): string {
  const lines: string[] = [];
  for (const m of messages) {
    const d = new Date((m.at ?? 0) * 1000);
    const p = (n: number) => String(n).padStart(2, '0');
    const stamp = `${p(d.getHours())}:${p(d.getMinutes())}:${p(d.getSeconds())}`;
    lines.push(`[${stamp}] from ${m.from ?? '?'}: ${m.body ?? ''}`);
  }
  return lines.join('\n');
}

// === SECTION === resuming a conversation in the relaunched process ===

/**
 * Flatten a stored conversation into (role, text) pairs for replay.
 *
 * `agent.messages` is the wire format — a mix of plain strings and lists of
 * content blocks — which is what the model needs but not what a transcript
 * pane shows. This walks it into the two things a reader recognises: what the
 * operator typed, and what the assistant answered. Tool traffic is dropped
 * rather than replayed: the tool panels are live progress, and a wall of them
 * for work already finished would bury the conversation.
 *
 * Pure, so the suite can test the walk without an app or a session file.
 */
export function transcriptOf(messages: ChatMessage[]): [string, string][] {
  const out: [string, string][] = [];
  for (const m of messages) {
    if (m.role !== 'user' && m.role !== 'assistant') continue;
    let text: string;
    if (typeof m.content === 'string') {
      text = m.content;
    } else {
      const parts: string[] = [];
      for (const b of m.content ?? []) {
        // Only prose. tool_use / tool_result blocks are deliberately
        // skipped — see the docstring.
        if (isTextBlock(b) && b.text) parts.push(b.text);
      }
      text = parts.join('\n');
    }
    text = text.trim();
    if (text) out.push([m.role, text]);
  }
  return out;
}

function isTextBlock(b: ContentBlock): b is { type: 'text'; text: string } {
  return typeof b === 'object' && b !== null && (b as { type?: string }).type === 'text';
}

// === SECTION === spawning ===

export function tmuxPaneId(): string | null {
  return process.env['TMUX_PANE'] || null;
}

/**
 * Make sure the server on `socket` is carrying this config's bindings.
 *
 * `tmux -f` is read only when a server STARTS. If one is already running on
 * the socket — left behind by an earlier run, or started by a bare
 * `tmux -L andy` — then `new-session -A` silently attaches to it and the
 * generated config is never read at all. The bindings are then tmux's stock
 * ones, under which ctrl+b h is not a prefix binding and does nothing
 * whatsoever. So the config is sourced into whatever server we find, whether
 * we started it or merely attached to it. Sourcing is idempotent: the file is
 * our own, regenerated on every launch.
 */
export function applyConfig(conf: string, socket: string = TMUX_SOCKET): void {
  const base = ['tmux', '-L', socket];
  // subprocess.call semantics: fire, ignore status. A missing tmux is
  // reported by launch()'s availability check, not here.
  spawnSync(base[0]!, [...base.slice(1), '-f', conf, 'start-server']);
  spawnSync(base[0]!, [...base.slice(1), 'source-file', conf]);
}

/**
 * Start (or attach to) the Andy tmux session with the pane bindings.
 *
 * `firstCmd` is what the INITIAL pane runs, when that should differ from
 * what the ctrl+b h/v bindings run. `/panes` uses it to resume the saved
 * conversation in the first pane only: panes opened afterwards are new
 * agents, and cloning the same history into each of them would defeat the
 * point of them being separate agents that message each other.
 *
 * Runs tmux in the foreground. Resolves to its exit status.
 */
export function launch(
  conf: string,
  andyCmd: string,
  workdir: string,
  firstCmd?: string | null,
): Promise<number> {
  if (!tmuxAvailable()) {
    return Promise.reject(new Error('tmux is not installed — `sudo apt install tmux`'));
  }
  applyConfig(conf);
  const argv = [
    'tmux',
    '-L',
    TMUX_SOCKET,
    '-f',
    conf,
    'new-session',
    '-A',
    '-s',
    TMUX_SESSION,
    '-c',
    workdir,
    firstCmd || andyCmd,
  ];
  return new Promise((resolve) => {
    const child = spawn(argv[0]!, argv.slice(1), { stdio: 'inherit' });
    child.on('close', (code) => resolve(code ?? 0));
    child.on('error', () => resolve(1));
  });
}
